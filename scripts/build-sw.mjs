// Builds public/sw.js from sw/policy.js + sw/sw.js. The build id is a hash of everything the worker depends on,
// so the file changes (and browsers update the worker) exactly when the worker or offline page changes.
import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";

const root = new URL("../", import.meta.url);
const read = (p) => readFile(new URL(p, root), "utf8");

const [policy, worker, offline] = await Promise.all([read("sw/policy.js"), read("sw/sw.js"), read("public/offline.html")]);
const buildId = createHash("sha256").update(policy).update(worker).update(offline).digest("hex").slice(0, 12);

const output = `/* GENERATED by scripts/build-sw.mjs. Do not edit; edit sw/*.js instead. */\nvar BUILD_ID = "${buildId}";\n${policy}\n${worker}`;
await writeFile(new URL("public/sw.js", root), output);
console.log(`public/sw.js built (build ${buildId})`);
